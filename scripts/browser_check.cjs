const assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')

async function run() {
  const browser = await chromium.launch({ headless: true })
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto('http://127.0.0.1:8001')
    await page.locator('.booking-panel').waitFor()
    const week = await page.getByLabel('Fecha de la agenda', { exact: true }).inputValue()
    const day = new Date(week + 'T12:00:00'); day.setDate(day.getDate() + 4)
    const iso = day.getFullYear() + '-' + String(day.getMonth() + 1).padStart(2, '0') + '-' + String(day.getDate()).padStart(2, '0')
    const form = page.locator('.booking-form')
    await form.getByRole('combobox', { name: 'Laboratorio', exact: true }).selectOption('1')
    await form.getByRole('combobox', { name: 'Curso / actividad' }).selectOption('1')
    await form.getByLabel('Fecha', { exact: true }).fill(iso)
    await form.getByLabel('Inicio', { exact: true }).fill('09:00')
    await form.getByLabel('Término', { exact: true }).fill('10:00')
    const posted1 = page.waitForResponse(r => r.url().endsWith('/api/reservas') && r.request().method() === 'POST')
    await page.getByRole('button', { name: 'Enviar solicitud', exact: true }).click()
    const response1 = await posted1; assert.equal(response1.status(), 201)
    const first = await response1.json()
    await page.getByRole('status').waitFor()
    await form.getByLabel('Inicio', { exact: true }).fill('09:30')
    await form.getByLabel('Término', { exact: true }).fill('10:30')
    const posted2 = page.waitForResponse(r => r.url().endsWith('/api/reservas') && r.request().method() === 'POST')
    await page.getByRole('button', { name: 'Enviar solicitud', exact: true }).click()
    const response2 = await posted2; assert.equal(response2.status(), 201)
    const second = await response2.json()
    await page.getByLabel('Perfil de demostración').selectOption('ADM001')
    await page.getByRole('heading', { name: 'Por aprobar', exact: true }).waitFor()
    await page.getByRole('button', { name: /^Solicitudes/ }).first().click()
    await page.locator('table tbody tr').first().waitFor()
    const rowAt = time => page.locator('tbody tr').filter({ has: page.locator('small', { hasText: time }) })
    const firstRow = rowAt('09:00–10:00')
    const approved = page.waitForResponse(r => r.url().endsWith('/' + first.id + '/aprobar'))
    await firstRow.getByRole('button', { name: 'Aprobar', exact: true }).click()
    assert.equal((await approved).status(), 200)
    await firstRow.getByText('Confirmada', { exact: true }).waitFor()
    const secondRow = rowAt('09:30–10:30')
    const conflict = page.waitForResponse(r => r.url().endsWith('/' + second.id + '/aprobar'))
    await secondRow.getByRole('button', { name: 'Aprobar', exact: true }).click()
    assert.equal((await conflict).status(), 409)
    await page.getByText('El horario ya no está disponible', { exact: true }).waitFor()
    await page.getByLabel('Perfil de demostración').selectOption('DOC001')
    await page.locator('.booking-panel').waitFor()
    await page.getByRole('button', { name: /Mis solicitudes/ }).click()
    await firstRow.getByRole('button', { name: 'Editar', exact: true }).click()
    const dialog = page.getByRole('dialog')
    await dialog.getByLabel('Inicio', { exact: true }).fill('08:00')
    await dialog.getByLabel('Término', { exact: true }).fill('09:00')
    const edited = page.waitForResponse(r => r.url().endsWith('/reservas/' + first.id) && r.request().method() === 'PATCH')
    await dialog.getByRole('button', { name: 'Guardar cambios' }).click()
    assert.equal((await edited).status(), 200)
    const modifiedRow = rowAt('08:00–09:00')
    await modifiedRow.getByRole('button', { name: 'Cancelar', exact: true }).click()
    const cancelled = page.waitForResponse(r => r.url().endsWith('/' + first.id + '/cancelar'))
    await page.getByRole('dialog').getByRole('button', { name: 'Sí, cancelar reserva' }).click()
    assert.equal((await cancelled).status(), 200)
    await modifiedRow.getByText('Cancelada', { exact: true }).waitFor()
    await page.getByLabel('Perfil de demostración').selectOption('DEL001')
    await page.locator('.booking-panel').waitFor()
    await form.getByRole('combobox', { name: 'Curso / actividad' }).selectOption('1')
    assert.equal(await form.getByRole('combobox', { name: 'Docente responsable' }).inputValue(), '1')
    assert.equal(await form.getByRole('combobox', { name: 'Curso / actividad' }).locator('option').count(), 2)
    await page.getByLabel('Perfil de demostración').selectOption('ADM001')
    await page.getByRole('heading', { name: 'Por aprobar', exact: true }).waitFor()
    await page.getByRole('button', { name: 'Laboratorios', exact: true }).click()
    await page.getByRole('button', { name: 'Nuevo laboratorio' }).click()
    const lf = page.getByRole('dialog')
    await lf.getByLabel('Código', { exact: true }).fill('LAB-TEST')
    await lf.getByLabel('Nombre', { exact: true }).fill('Laboratorio de Prueba')
    await lf.getByLabel('Ubicación').fill('Pabellón Test')
    const createdLab = page.waitForResponse(r => r.url().endsWith('/laboratorios') && r.request().method() === 'POST')
    await lf.getByRole('button', { name: 'Guardar laboratorio' }).click()
    assert.equal((await createdLab).status(), 201)
    await page.getByRole('heading', { name: 'Laboratorio de Prueba' }).waitFor()
    await page.getByRole('button', { name: 'Reportes', exact: true }).click()
    await page.getByRole('heading', { name: 'Reservas confirmadas por laboratorio' }).waitFor()
    await page.setViewportSize({ width: 390, height: 844 })
    await page.getByRole('button', { name: 'Reservas', exact: true }).click()
    await page.locator('.mobile-days').waitFor()
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    assert.equal(await page.locator('.day-column:visible').count(), 1)
    assert.deepEqual(errors, [])
    console.log('OK: frontend → API → SQLite. Solicitud, aprobación, 409, edición, cancelación, delegado, catálogo, reportes y móvil.')
  } finally { await browser.close() }
}
run().catch(error => { console.error(error); process.exitCode = 1 })
